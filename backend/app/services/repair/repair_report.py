from pathlib import Path
from difflib import unified_diff


class RepairReporter:
    """
    Creates and stores a complete report whenever
    AutoDev-AI repairs a generated project.
    """

    def __init__(self, project_path: str):

        self.project = Path(project_path).resolve()

        self.folder = self.project / "repair"

        self.folder.mkdir(
            parents=True,
            exist_ok=True,
        )

    def save(
        self,
        old_code: str,
        new_code: str,
        debug_report: str | dict | None,
    ):
        """
        Save:
        1. Original generated code
        2. Repaired code
        3. Code difference
        4. AI repair report
        """

        # --------------------------------------------------
        # Normalize debug report
        # --------------------------------------------------

        if debug_report is None:

            debug_text = "No debug report was generated."

        elif isinstance(debug_report, dict):

            debug_text = self._dict_to_text(
                debug_report
            )

        else:

            debug_text = str(debug_report)

        # --------------------------------------------------
        # Save old code
        # --------------------------------------------------

        old_code_file = self.folder / "old_code.txt"

        old_code_file.write_text(
            old_code or "",
            encoding="utf-8",
        )

        # --------------------------------------------------
        # Save new code
        # --------------------------------------------------

        new_code_file = self.folder / "new_code.txt"

        new_code_file.write_text(
            new_code or "",
            encoding="utf-8",
        )

        # --------------------------------------------------
        # Generate diff
        # --------------------------------------------------

        diff = unified_diff(
            (old_code or "").splitlines(),
            (new_code or "").splitlines(),
            fromfile="before",
            tofile="after",
            lineterm="",
        )

        diff_text = "\n".join(diff)

        diff_file = self.folder / "diff.patch"

        diff_file.write_text(
            diff_text,
            encoding="utf-8",
        )

        # --------------------------------------------------
        # Generate repair report
        # --------------------------------------------------

        report = f"""# AutoDev-AI Repair Report

## Repair Status

AI automatically repaired the generated project after execution failed.

---

## Debug Report

{debug_text}

---

## Code Changes

The AI generated a corrected version of the project.

### Original Code

Saved in:

`repair/old_code.txt`

### Repaired Code

Saved in:

`repair/new_code.txt`

### Code Difference

Saved in:

`repair/diff.patch`

---

## Repair Files

| File | Description |
|---|---|
| `old_code.txt` | Code before AI repair |
| `new_code.txt` | Code after AI repair |
| `diff.patch` | Difference between old and new code |
| `repair_report.md` | Complete repair information |

---

## Generated By

AutoDev-AI Autonomous Software Engineering System
"""

        report_file = self.folder / "repair_report.md"

        report_file.write_text(
            report,
            encoding="utf-8",
        )

        return {
            "repair_folder": str(self.folder),
            "old_code": str(old_code_file),
            "new_code": str(new_code_file),
            "diff": str(diff_file),
            "report": str(report_file),
        }

    # --------------------------------------------------
    # Helper
    # --------------------------------------------------

    @staticmethod
    def _dict_to_text(data: dict) -> str:

        lines = []

        for key, value in data.items():

            lines.append(
                f"### {key.replace('_', ' ').title()}\n\n"
                f"{value}\n"
            )

        return "\n".join(lines)